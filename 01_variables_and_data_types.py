# Lesson 1: Variables and Data Types

name = "David"
age = 25
height = 1.78
is_student = True

print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Is student:", is_student)

# Type conversion
number_as_string = "42"
converted_number = int(number_as_string)
print("Converted number:", converted_number + 8)

# String formatting
print(f"Hello, {name}! You are {age} years old.")
