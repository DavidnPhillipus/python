# Type Casting in Python
# Type casting means converting one data type into another.

x = 10
print(type(x))

# int to float
x = float(x)
print(x)
print(type(x))

# float to int
price = 49.99
price = int(price)
print(price)
print(type(price))

# string to int
number = "25"
number = int(number)
print(number)
print(type(number))

# string to float
value = "3.14"
value = float(value)
print(value)
print(type(value))

# int to string
age = 30
age = str(age)
print(age)
print(type(age))

# bool to int
flag = True
print(int(flag))
